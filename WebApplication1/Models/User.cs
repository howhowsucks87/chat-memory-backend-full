namespace WebApplication1.Models
{
    // ==========================================================
    // User
    // ----------------------------------------------------------
    // 功能：
    // 1️⃣ 系統的使用者帳號資料
    // 2️⃣ 作為認證（JWT）的主體
    // 3️⃣ 與其他資料表建立關聯（ChatMessage / Memory）
    //
    // 在資料庫中對應：
    // Table: Users
    //
    // 關聯：
    // User (1) → (Many) ChatMessage
    // User (1) → (Many) Memory
    // ==========================================================
    public class User
    {
        // ----------------------------------------------------------
        // 主鍵（Primary Key）
        // ----------------------------------------------------------
        // EF Core 會自動將 Id 視為主鍵
        // 通常在資料庫為：
        // INT IDENTITY (1,1)
        //
        // ⚠️ 不應由前端傳入
        // 必須由資料庫自動產生
        public int Id { get; set; }


        // ----------------------------------------------------------
        // Email（登入帳號）
        // ----------------------------------------------------------
        // 作為使用者的唯一識別帳號
        //
        // ⚠️ 設計重點：
        // 1️⃣ 必須唯一（資料庫要加 Unique Index）
        // 2️⃣ 建議儲存前轉小寫（避免大小寫重複）
        // 3️⃣ 建議限制最大長度（例如 255）
        //
        // 在 DbContext 應設定：
        // .HasIndex(u => u.Email).IsUnique();
        //
        // ⚠️ 不建議將 Email 作為主鍵
        // 原因：
        // - Email 可能會變更
        // - 主鍵應保持穩定
        public string Email { get; set; } = null!;


        // ----------------------------------------------------------
        // PasswordHash（密碼雜湊）
        // ----------------------------------------------------------
        // 儲存經過雜湊（Hash）處理後的密碼
        //
        // ⚠️ 極重要安全原則：
        // 1️⃣ 絕對不能存明碼密碼
        // 2️⃣ 必須使用安全雜湊演算法（例如 BCrypt）
        // 3️⃣ 不可自行實作 Hash
        //
        // 註冊流程：
        // PasswordHash = BCrypt.HashPassword(dto.Password);
        //
        // 登入驗證：
        // BCrypt.Verify(dto.Password, user.PasswordHash);
        //
        // ⚠️ 不可：
        // - 回傳給前端
        // - 寫入 Log
        // - 在錯誤訊息中顯示
        //
        // 建議限制欄位長度（例如 200）
        public string PasswordHash { get; set; } = null!;


        // ----------------------------------------------------------
        // 建立時間（UTC）
        // ----------------------------------------------------------
        // 使用 UTC 避免時區問題
        //
        // ⚠️ 建議整個專案統一使用 UTC
        // 顯示給前端時再轉換為當地時間
        //
        // 若資料庫也有 DefaultValue
        // 需避免雙重設定
        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
    }
}