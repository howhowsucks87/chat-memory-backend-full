namespace ChatMemoryApi.Models
{
    // ==========================================================
    // ChatMessage
    // ----------------------------------------------------------
    // 功能：
    // 1️⃣ 儲存使用者的聊天訊息
    // 2️⃣ 與 User 建立關聯（多對一）
    // 3️⃣ 作為對話紀錄資料表
    //
    // 在資料庫中會對應為：
    // Table: ChatMessages
    //
    // 關聯關係：
    // 一個 User 可以有 多個 ChatMessage
    // 一個 ChatMessage 只屬於 一個 User
    // ==========================================================
    public class ChatMessage
    {
        // ----------------------------------------------------------
        // 主鍵（Primary Key）
        // ----------------------------------------------------------
        // EF Core 會自動辨識 "Id" 為主鍵
        // 通常會對應為：
        // INT IDENTITY (1,1)
        //
        // ⚠️ 不建議讓前端傳入 Id
        // 由資料庫自動產生
        public int Id { get; set; }


        // ----------------------------------------------------------
        // 外鍵（Foreign Key）
        // ----------------------------------------------------------
        // 指向 User.Id
        //
        // 這是實際存在於資料庫的欄位
        // 用來建立 User 與 ChatMessage 的關聯
        //
        // ⚠️ 必須確保：
        // - 有對應的 User
        // - 不要讓前端隨便指定別人的 UserId
        //
        // 建議：
        // - 從 JWT 取得 UserId
        // - 不要從 DTO 接收 UserId
        public int UserId { get; set; }


        // ----------------------------------------------------------
        // 訊息內容
        // ----------------------------------------------------------
        // 使用者輸入的聊天文字
        public string Content { get; set; } = null!;


        // ----------------------------------------------------------
        // 建立時間（UTC）
        // ----------------------------------------------------------
        // 使用 DateTime.UtcNow 避免時區問題
        //
        // ⚠️ 注意：
        // 1️⃣ 如果資料庫也有 DefaultValue，可能會衝突
        // 2️⃣ 建議整個專案統一使用 UTC
        //
        // 顯示給前端時再轉換為本地時間
        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;


        // ----------------------------------------------------------
        // 導覽屬性（Navigation Property）
        // ----------------------------------------------------------
        // 代表關聯的 User 物件
        //
        // EF Core 會透過：
        // - UserId
        // - User
        // 自動推斷關聯
        //
        // 如果使用 Include：
        // _db.ChatMessages.Include(c => c.User)
        //
        // 就可以同時取得 User 資料
        //
        // ⚠️ 注意 Lazy Loading：
        // 如果未啟用 Lazy Loading
        // 需要手動 Include
        public User User { get; set; } = null!;
    }
}