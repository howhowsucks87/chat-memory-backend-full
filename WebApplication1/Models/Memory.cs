namespace WebApplication1.Models
{
    // ==========================================================
    // Memory
    // ----------------------------------------------------------
    // 功能：
    // 1️⃣ 儲存使用者的「長期記憶」或對話摘要
    // 2️⃣ 可用於 RAG（Retrieval-Augmented Generation）
    // 3️⃣ 用來減少模型上下文長度限制問題
    //
    // 在資料庫中對應：
    // Table: Memories
    //
    // 關聯關係：
    // 一個 User 可以擁有多個 Memory
    // 一個 Memory 只屬於一個 User
    // ==========================================================
    public class Memory
    {
        // ----------------------------------------------------------
        // 主鍵（Primary Key）
        // ----------------------------------------------------------
        // EF Core 會自動將 Id 當作主鍵
        // 通常會在資料庫中設定為：
        // INT IDENTITY (1,1)
        //
        // ⚠️ 不應由前端傳入
        // 應由資料庫自動產生
        public int Id { get; set; }


        // ----------------------------------------------------------
        // 外鍵（Foreign Key）
        // ----------------------------------------------------------
        // 指向 User.Id
        //
        // 此欄位實際存在於資料庫中
        // 用來建立 User 與 Memory 的關聯
        //
        // ⚠️ 安全性注意：
        // - 不要從前端直接接收 UserId
        // - 應從 JWT Claim 取得目前登入者 Id
        //
        // 例如：
        // var userId = User.FindFirstValue(JwtRegisteredClaimNames.Sub);
        public int UserId { get; set; }


        // ----------------------------------------------------------
        // Summary（摘要內容）
        // ----------------------------------------------------------
        // 儲存 AI 產生的對話摘要或長期記憶內容
        //
        // 可能包含：
        // - 使用者偏好
        // - 對話重點
        // - 任務紀錄
        //
        // ⚠️ 注意事項：
        // 1️⃣ 內容可能很長（建議限制長度）
        // 2️⃣ 若會顯示在前端，需防止 XSS
        // 3️⃣ 不建議無限制 nvarchar(max)
        //
        // 建議在 DbContext 中加：
        // .Property(m => m.Summary)
        // .HasMaxLength(2000);
        //
        // 如果未來要做向量搜尋：
        // - 這裡可搭配 Embedding 欄位
        public string Summary { get; set; } = null!;


        // ----------------------------------------------------------
        // 建立時間（UTC）
        // ----------------------------------------------------------
        // 使用 UTC 避免跨時區問題
        //
        // ⚠️ 建議整個專案統一使用 UTC
        // 顯示給前端時再轉換為當地時間
        //
        // 如果資料庫也設定 DefaultValue
        // 需避免雙重設定衝突
        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;


        // ----------------------------------------------------------
        // 導覽屬性（Navigation Property）
        // ----------------------------------------------------------
        // 代表關聯的 User 物件
        //
        // EF Core 會透過：
        // - UserId
        // - User
        // 自動建立關聯
        //
        // 如果使用：
        // _db.Memories.Include(m => m.User)
        //
        // 就會同時載入 User 資料
        //
        // ⚠️ 若未使用 Include，且未啟用 Lazy Loading
        // User 會是 null
        public User User { get; set; } = null!;
    }
}