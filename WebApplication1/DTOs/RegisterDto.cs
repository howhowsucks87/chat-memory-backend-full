using System.ComponentModel.DataAnnotations;

namespace ChatMemoryApi.DTOs
{
    // ==========================================================
    // RegisterDto
    // ----------------------------------------------------------
    // 功能：
    // 1️⃣ 接收前端傳來的註冊資料
    // 2️⃣ 作為 API 的輸入模型
    // 3️⃣ 與資料庫 Entity（User）分離
    //
    // 為什麼要使用 DTO？
    // ----------------------------------------------------------
    // ❌ 如果直接使用 User Entity：
    //    - 前端可能傳入 Id、CreatedAt 等不該填的欄位
    //    - 可能被惡意覆蓋 PasswordHash
    //    - 會暴露內部資料結構
    //
    // ✅ 使用 DTO 可以：
    //    - 僅允許 Email / Password
    //    - 保持 API 邊界乾淨
    //    - 降低資安風險
    // ==========================================================
    public class RegisterDto
    {
        // ----------------------------------------------------------
        // Email
        // ----------------------------------------------------------
        // 使用者的登入帳號（必須唯一）
        //
        // 目前使用 null!：
        // - 告訴編譯器這個值不會為 null
        // - 實際是否為 null 應由 Model Validation 控制
        [Required]
        [EmailAddress]
        [MaxLength(255)]
        public string Email { get; set; } = null!;


        // ----------------------------------------------------------
        // Password
        // ----------------------------------------------------------
        // 使用者輸入的「明碼密碼」
        //
        // ⚠️ 極度重要：
        // 1️⃣ 絕對不能存明碼
        // 2️⃣ 必須透過 BCrypt / PBKDF2 等演算法 Hash
        // 3️⃣ 不可回傳給前端
        // 4️⃣ 不可寫入 Log
        //
        // 註冊時的安全考量：
        // - 密碼長度限制
        // - 複雜度檢查
        // - 防止超長字串攻擊
        [Required]
        [MinLength(8)]
        [MaxLength(100)]
        public string Password { get; set; } = null!;
    }
}