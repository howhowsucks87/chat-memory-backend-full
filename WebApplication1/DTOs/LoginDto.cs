using System.ComponentModel.DataAnnotations;

namespace WebApplication1.DTOs
{
    // ==========================================================
    // LoginDto
    // ----------------------------------------------------------
    // DTO = Data Transfer Object
    //
    // 功能：
    // 1️⃣ 接收前端傳來的登入資料
    // 2️⃣ 作為 API 的輸入模型
    // 3️⃣ 與資料庫 Entity 分離（避免過度暴露資料）
    //
    // 為什麼不能直接用 User Entity？
    // ----------------------------------------------------------
    // ❌ 如果直接用 User：
    //    - 前端可以傳不該有的欄位（例如 Id、CreatedAt）
    //    - 可能被惡意注入資料
    //    - 密碼 Hash 可能被覆蓋
    //
    // ✅ 使用 DTO 可以：
    //    - 僅暴露必要欄位
    //    - 限制輸入資料結構
    //    - 提升安全性
    // ==========================================================
    public class LoginDto
    {
        // ----------------------------------------------------------
        // Email
        // ----------------------------------------------------------
        // 使用者登入帳號
        //
        // 目前使用 null! 的意思是：
        // 「告訴編譯器這個值不會是 null」
        //
        // 因為：
        // - ASP.NET Core Model Binding 會自動填值
        // - 如果未填值，應由模型驗證處理
        [Required]
        [EmailAddress]
        [MaxLength(255)]
        public string Email { get; set; } = null!;


        // ----------------------------------------------------------
        // Password
        // ----------------------------------------------------------
        // 使用者輸入的「明碼密碼」
        //
        // ⚠️ 非常重要：
        // 1️⃣ 這裡是明碼
        // 2️⃣ 絕對不能存入資料庫
        // 3️⃣ 必須透過 BCrypt 驗證
        //
        // 安全注意事項：
        // - 不要在 Log 中輸出 Password
        // - 不要回傳到前端
        // - 不要在 Exception 中顯示
        [Required]
        [MinLength(8)]
        public string Password { get; set; } = null!;
    }
}